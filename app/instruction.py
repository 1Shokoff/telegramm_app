"""Инструкция по установке: один шаблон для витрины и для чата бота.

Продавец не пишет инструкцию каждый раз заново — он отправляет этот шаблон
и при желании добавляет примечание к конкретному заказу.

Шаг описывается данными, а не картинкой: витрина рисует по ним карточку
с макетом переписки. Так инструкция весит килобайты, читается на любом
экране и правится текстом здесь же.

Виды строк в макете переписки (chat):
    bot    — сообщение бота
    user   — сообщение покупателя
    button — кнопка под сообщением
    file   — вложенный файл, meta — его размер
"""
from __future__ import annotations

REGER_BOT = "iRegerBot"
SIGNER_BOT = "isignerbot"

# Боты, на которые ведут ссылки в начале инструкции.
BOTS = (
    {"username": REGER_BOT, "title": "iReg", "hint": "регистрация UDID и сертификат"},
    {"username": SIGNER_BOT, "title": "iSign", "hint": "подпись и установка приложения"},
)


def _step(title, subtitle, hint, bot, chat):
    return {"title": title, "subtitle": subtitle, "hint": hint, "bot": bot, "chat": chat}


def _bot(text):
    return {"kind": "bot", "text": text}


def _user(text):
    return {"kind": "user", "text": text}


def _button(text):
    return {"kind": "button", "text": text}


def _file(text, meta, mine=False):
    return {"kind": "file", "text": text, "meta": meta, "mine": mine}


STEPS = (
    _step(
        "Введите свой UDID",
        "Откройте @%s и отправьте UDID" % REGER_BOT,
        "Используйте UDID из вашего заказа",
        "iReg",
        [
            _user("/start"),
            _bot("Отправьте UDID"),
            _user("00008110-001A18411E22801E"),
        ],
    ),
    _step(
        "Получите сертификат",
        "Нажмите «Получить сертификат»",
        "Сохраните .p12, .mobileprovision и пароль",
        "iReg",
        [
            _bot("UDID: 00008110-001A18411E22801E\nДобавлен: 02/06/2025\nСтатус: Активен 🟢\nИмя: jing wen meng"),
            _button("⬇️ Получить сертификат (jing wen meng)"),
            _file("00008110-001A18411E22801E.p12", "3,1 КБ"),
            _file("00008110-001A18411E22801E.mobileprovision", "17,6 КБ"),
            _bot("Пароль: 1"),
        ],
    ),
    _step(
        "Добавьте сертификат",
        "@%s → «Мои сертификаты» → «Добавить»" % SIGNER_BOT,
        "Дальше бот попросит файлы по очереди",
        "iSign",
        [
            _user("/start"),
            _bot("Выберите одну из опций ниже."),
            _button("Подписать iPA"),
            _button("Мои сертификаты"),
            _bot("Ваши сертификаты"),
            _button("Добавить"),
        ],
    ),
    _step(
        "Отправьте файл .p12",
        "Перешлите файл из @%s в @%s" % (REGER_BOT, SIGNER_BOT),
        "Выберите файл с расширением .p12",
        "iSign",
        [
            _bot("Отправьте .p12 файл ⏳"),
            _file("00008110-001A18411E22801E.p12", "3,1 КБ", mine=True),
            _bot("Отправьте мне пароль 🔒\nЕсли на сертификате нет пароля — нажмите «Пропустить»"),
            _button("Пропустить"),
        ],
    ),
    _step(
        "Введите пароль",
        "Возьмите пароль из сообщения с сертификатом",
        "В примере пароль — 1, ваш может отличаться",
        "iSign",
        [
            _bot("Отправьте мне пароль 🔒"),
            _user("1"),
            _bot("Отправьте .mobileprovision файл"),
        ],
    ),
    _step(
        "Отправьте .mobileprovision",
        "Перешлите второй файл из @%s" % REGER_BOT,
        "Дождитесь сообщения «Сертификат добавлен»",
        "iSign",
        [
            _file("00008110-001A18411E22801E.mobileprovision", "17,6 КБ", mine=True),
            _bot("Сертификат добавлен ✅"),
            _button("Назад"),
        ],
    ),
    _step(
        "Нажмите «Подписать iPA»",
        "В меню @%s выберите подпись приложения" % SIGNER_BOT,
        "Если появится второе меню — снова «Подписать iPA»",
        "iSign",
        [
            _user("/start"),
            _bot("Выберите дополнительные опции ниже:"),
            _button("Изменить BundleID"),
            _button("Подписать iPA"),
        ],
    ),
    _step(
        "Отправьте приложение",
        "Отправьте нужный файл в формате .ipa",
        "Дождитесь завершения загрузки файла",
        "iSign",
        [
            _bot("Отправьте .ipa файл"),
            _file("Приложение.ipa", "170,5 МБ", mine=True),
            _bot("Downloaded: 170.53 MB\n100%"),
        ],
    ),
    _step(
        "Выберите свой сертификат",
        "Если бот предложит выбрать сертификат",
        "Сверьте название с сообщением @%s" % REGER_BOT,
        "iSign",
        [
            _bot("Выберите сертификат ниже:"),
            _button("jing wen meng"),
            _button("Другой"),
        ],
    ),
    _step(
        "Установите приложение",
        "После подписи нажмите «Установить»",
        "Дальше следуйте подсказкам установки на iPhone",
        "iSign",
        [
            _bot("Файл подписан 🟢\nСсылка действительна 1 неделю"),
            _button("Установить ✅"),
        ],
    ),
)


def public_steps() -> list[dict]:
    """Шаги для витрины: к тексту добавлен номер."""
    return [dict(step, number=i) for i, step in enumerate(STEPS, start=1)]


def bot_links() -> list[dict]:
    return [dict(bot, url="https://t.me/%s" % bot["username"]) for bot in BOTS]
