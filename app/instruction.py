"""Инструкция по установке: один шаблон для витрины и для чата бота.

Продавец не пишет инструкцию каждый раз заново — он отправляет этот шаблон
и при желании добавляет примечание к конкретному заказу.

Тексты шагов лежат здесь, кадр переписки — картинкой в
webapp/img/instruction/step-NN.webp, остальное оформление карточки рисует
витрина. Так текст правится в одном месте, а вид карточки — в стилях.
"""
from __future__ import annotations

REGER_BOT = "iRegerBot"
SIGNER_BOT = "isignerbot"

# Боты, на которые ведут ссылки в начале инструкции.
BOTS = (
    {"username": REGER_BOT, "title": "iReg", "hint": "регистрация UDID и сертификат"},
    {"username": SIGNER_BOT, "title": "iSign", "hint": "подпись и установка приложения"},
)


def _step(title: str, subtitle: str, hint: str) -> dict:
    """Шаг: что сделать, как именно и подпись под кадром."""
    return {"title": title, "subtitle": subtitle, "hint": hint}


STEPS = (
    _step(
        "Введите свой UDID",
        "Откройте @%s и отправьте UDID" % REGER_BOT,
        "Используйте UDID из вашего заказа",
    ),
    _step(
        "Получите сертификат",
        "Нажмите «Получить сертификат»",
        "Сохраните .p12, .mobileprovision и пароль",
    ),
    _step(
        "Добавьте сертификат",
        "@%s → «Мои сертификаты» → «Добавить»" % SIGNER_BOT,
        "Дальше бот попросит файлы по очереди",
    ),
    _step(
        "Отправьте файл .p12",
        "Перешлите файл из @%s в @%s" % (REGER_BOT, SIGNER_BOT),
        "Выберите файл с расширением .p12",
    ),
    _step(
        "Введите пароль",
        "Возьмите пароль из сообщения с сертификатом",
        "В кадре — пример, ваш пароль может отличаться",
    ),
    _step(
        "Отправьте .mobileprovision",
        "Перешлите второй файл из @%s" % REGER_BOT,
        "Дождитесь сообщения «Сертификат добавлен»",
    ),
    _step(
        "Нажмите «Подписать iPA»",
        "В меню @%s выберите подпись приложения" % SIGNER_BOT,
        "Если появится второе меню — снова «Подписать iPA»",
    ),
    _step(
        "Отправьте приложение",
        "Отправьте нужный файл в формате .ipa",
        "Дождитесь завершения загрузки файла",
    ),
    _step(
        "Выберите свой сертификат",
        "Если бот предложит выбрать сертификат",
        "Сверьте название с сообщением @%s" % REGER_BOT,
    ),
    _step(
        "Установите приложение",
        "После подписи нажмите «Установить»",
        "Дальше следуйте подсказкам установки на iPhone",
    ),
)


def image(number: int) -> str:
    """Кадр переписки для шага в статике Mini App."""
    return "/static/img/instruction/step-%02d.webp" % number


def public_steps() -> list[dict]:
    """Шаги для витрины: к тексту добавлены номер и кадр."""
    return [
        dict(step, number=i, image=image(i))
        for i, step in enumerate(STEPS, start=1)
    ]


def bot_links() -> list[dict]:
    return [dict(bot, url="https://t.me/%s" % bot["username"]) for bot in BOTS]
